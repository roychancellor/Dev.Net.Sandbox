def createJWT():

  # Load the private key
  try:
    private_key = open(keystore_PrivateKeyFile).read().encode()

    # if the private key is password protected:
    passphrase = open(keystore_PassPhraseFile).read().rstrip('\n').encode()
    # otherwise:
    #passphrase = None

    key = serialization.load_pem_private_key(
      private_key, password=passphrase, backend=default_backend()
    )
  except:
    print('Unable to extract private key from keystore', file=sys.stderr)
    return None

  # Get the current time as a Unix time stamp
  now = int(time.time())

  # Set the mandatory claims for the JWT
  claims = dict()
  claims['iss'] = orgId                     # the issuer must be something unique
  claims['iat'] = now                       # issued at the current time
  claims['exp'] = now + 3600 * 24 * 30      # expiry in one hour, you could use other values
  claims['authorities'] = ['ROLE_SEARCH']   # mandatory for EDB
  claims['orgId'] = orgId                   # mandatory for EDB
  claims['user_name'] = 'testscript'        # should reflect the actual user making the query

  # Generate the JWT
  encoded_jwt = jwt.encode(claims, key, algorithm='RS256')
  return encoded_jwt.decode('ascii')


