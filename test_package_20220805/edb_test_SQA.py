def initiateSearch (jwt, query, incidentId):

  """
    Initiate a search to retrieve information relevant to a location,
    telephone number, civic address and an optional list of search types.
    This search is done asynchronously and this call returns immediately
    with a SWL which can be used to view the search results.

    Path:    https://[BrokerBaseUrl]/v1/initiate-search
    Method:  POST
    Body:    see below for details

    Headers:

      Header Name    | Required | Header Value
      ---------------+----------+----------------------------------------------
      Authorization  | Yes      | JWT
      IncidentId     | Yes      | Unique Id for call
      StationUser    | No       | Caller username
      StationId      | No       | Caller station
      Content-Type   | Yes      | “application/json”
      TransactionId  | No       | Optional ID to track API call in server log


    Searches accept query bodies as follows:

      { “location”: {
          "datum": <geodetic datum>,
          “latitude”: <decimal degrees from equator>,
          “longitude": <decimal degrees from prime meridian>,
          "altitude": <meters above sea level>,
          "uncertainty": <percentage>,
          "confidence": {
            "value": <string>,
            "pdf": <string>
          }
        },
        “phone”: <10 digit phone#>,
        "address": {
          "A1": <state, two-characters>,
          "A2": <county>,
          "A3": <city>,
          "RD": <street>,
          "STS": <street suffix>,
          "POD": <trailing street suffix>,
          "HNO": <house number>,
          "LOC": <location>,
          "PC": <postal code>
        }
        "searchTypes": [list of search types]
      }

      All values in this structure are optional in the sense that the API does not enforce
      their presence. However, each search type requires certain fields in order to work.
      The address structure can contain any of the PDIF-LO fields.

      The list of Search Types can change. The current list of search types includes the
      following:
        - Safety Shield       (requires location)
        - Alarm               (requires phone, location is optional)
        - Commercial Phone    (requires phone)
        - Commercial Locate   (requires location and phone)
        - Commercial Address  (requires address)
        - Telematics sim      (requires location)
  """

  url = baseUrl + '/v1/initiate-search'

  headers = {
    'Authorization': "Bearer " + jwt,
    'IncidentId': incidentId,
    'Content-Type': 'application/json'
  }

  if verbose:
    print("----- initiateSearch request -----")
    print("url:", url)
    print("headers:", headers)
    print("data:", query)

  r = requests.post(url, data=json.dumps(query), headers=headers)

  if verbose:
    print("----- initiateSearch response -----")
    print("status code:", r.status_code)
    print("headers:", r.headers)
    print("body:", r.text)

  if r.status_code == 200:
    # Extract Security Word from previous result
    m = re.search("^http.*/(\w\w\w\d\d|\d\d\w\w\w)$", r.text)
    if m:
      if verbose:
        print("Security Word:", m[1])
      return m[1]
    else:
      print("cannot extract Security Word", file=sys.stderr)
      return None

  else:
    print("InitiateSearch failed", file=sys.stderr)
    return None
  

