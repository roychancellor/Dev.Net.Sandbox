def retrieveAdditionalData (jwt, uniqueSearchId, index, fileName, threadId):

  """
    Search for additional data related to a previous search. Providers
    may be configured to provide additional streamed data related to a
    previous search. If so, this call will return that data stream. If the
    incident is in-progress, then the stream will stay active until the
    incident is CLOSED (since more searches may be made for the
    incident). Note that a SSE event value of "PING" is sent periodically
    with an empty data element to prevent socket timeouts for long
    running streams.

    Path:    https://[BrokerBaseUrl]/v1/additional-data-search
    Method:  GET
    Body:    none

    Query Parameters:
      SearchId:     This the value corresponding to the "uniqueSearchId"
                    name in a (prior) search result payload JSON response.
      ResultIndex:  Required for providers that return an array of
                    results corresponding to a search ID, this
                    index specifies which result to return
                    additional data for.

    Headers:

      Header Name    | Required | Header Value
      ---------------+----------+----------------------------------------------
      Authorization  | Yes      | JWT
      Accept         | No       | text/event-stream
      TransactionId  | No       | Optional ID to track API call in server log
  """

  url = baseUrl + '/v1/additional-data-search'

  headers = {
    'Authorization': "Bearer " + jwt,
    'Accept': 'text/event-stream'
  }

  parameters = {
    'SearchId': uniqueSearchId
  }
  if index >= 0:
    parameters['ResultIndex'] = index

  fn = fileName + '_' + threadId

  r = requests.get(url, params=parameters, headers=headers, stream=True)

  if verbose:
    print(threadId, "result index:", index)
    print(threadId, "status code:", r.status_code)
    print(threadId, "headers:", r.headers)
    print(threadId, "writing to file", fn)

  #----- Process the result -----
  for line in r.iter_lines():
    line = line.decode()
    if printResults:
      print(threadId, "line", line)

    if line[:4] == 'data' and line[5:] != '{}':
      # Parse result as JSON
      jline = json.loads(line[5:])
      # Print result to file
      f = open(fn, "a")
      f.write(json.dumps(jline, indent=2) + "\n")
      f.close()


