def retrieveData (jwt, securityWord, fileName, additionalData):

  """
    Retrieve search results for a Short Web Link for an authenticated user.

    Path:    https://[BrokerBaseUrl]/v1/retrieve-swl-data
    Method:  GET
    Body:    none

    Query Parameters:
      SecurityWord:  Security Word corresponding to the SWL. The Security Word is
                     a unique (at any given time) identifier for the search results
                     for a given call or incident, and is the last component of the SWL.

    Headers:

      Header Name    | Required | Header Value
      ---------------+----------+----------------------------------------------
      Authorization  | Yes      | JWT
      Accept         | No       | text/event-stream
      TransactionId  | No       | Optional ID to track API call in server log
  """

  url = baseUrl + '/v1/retrieve-swl-data'

  headers = {
    'Authorization': "Bearer " + jwt,
    'Accept': 'text/event-stream'
  }

  parameters = {
    'SecurityWord': securityWord
  }

  r = requests.get(url, params=parameters, headers=headers, stream=True)

  if verbose:
    print("----- retrieveData response -----")
    print("status code:", r.status_code)
    print("headers:", r.headers)
    print("writing to file", fileName)

  #----- Process the result -----
  threadCounter = 0
  for line in r.iter_lines():
    line = line.decode()
    if printResults:
      print("line", line)

    if line[:4] == 'data' and line[5:] != '{}':
      # Parse result as JSON
      jline = json.loads(line[5:])
      # Print result to file
      f = open(fileName, "a")
      f.write(json.dumps(jline, indent=2) + "\n")
      f.close()

      # If needed, launch 'additional-data-search' in separate threads.
      # The additional data streams do not close when 'terminate' is called.
      # The threads are started with daemon=True so they get terminated when
      # this program finishes.
 
      if additionalData:
        try:
          uniqueSearchId = jline['data']['uniqueSearchId']
          searchResult = jline['data']['searchResult']

          # 'searchResult' contains either a JSON document with a single result
          # or an element 'results' containing an array. If we have the latter,
          # we need to perform multiple searches.

          sequence = [-1]  # default in case we don't have an array

          if 'results' in searchResult:
            results = searchResult['results']
            # Check whether we reveived an array
            if type(results).__name__ == 'list':
              # Array: call retrieveAdditionalData for each element
              sequence = range(0, len(results))

          for i in sequence:
            threadCounter = threadCounter + 1
            threadId = str(threadCounter).zfill(4)
            t = Thread(target=retrieveAdditionalData, args=(jwt, uniqueSearchId, i, fileName, threadId), daemon=True)
            t.start()
        except:
          pass

