def terminateCall (jwt, incidentId):

  """
    Notifies EDB that a call has terminated and no more searches related to
    this incident will be requested. This will terminate streaming of all EDB
    search results related to the incident.

    Path:    https://[BrokerBaseUrl]/v1/terminate/[incidentId]
    Method:  DELETE
    Body:    none

    Headers:

      Header Name    | Required | Header Value
      ---------------+----------+----------------------------------------------
      Authorization  | Yes      | JWT
      StationUser    | No       | Caller username
      StationId      | No       | Caller station
      TransactionId  | No       | Optional ID to track API call in server log
  """

  url = baseUrl + '/v1/terminate/' + incidentId

  headers = {
    'Authorization': "Bearer " + jwt
  }

  r = requests.delete(url, headers=headers)

  if verbose:
    print("----- terminateCall response -----")
    print("status code:", r.status_code)


#------------------------------------------------------------------------------------------------------

def waitAndTerminate(seconds, jwt, incidentId):

  # Sleep for some time, then call "terminate"
  time.sleep(seconds)
  if verbose:
    print("terminating")
  terminateCall (jwt, incidentId)


