def usage():

  print ('Usage: ' + sys.argv[0] + '\n',
         '       -h | --help            show this help and exit\n',
         '       -v | --verbose         display details about the query progress\n',
         '       -p | --print           print results on the console (results are always logged in a file)\n',
         '       -w | --wait     [n]    wait for n seconds until a terminate is sent, default: 15s\n',
         '       -q | --query    [id]   use predefied query sample')


