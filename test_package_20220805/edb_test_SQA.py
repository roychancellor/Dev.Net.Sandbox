#!/usr/bin/python3

"""
  This sample code demonstrates how to use Intrado's Emergency Data Broker API.
  It shows how to initiate a search and how to retrieve a stream of results.
  In addition, it shows how to terminate an event and how to generate the 
  necessary JWT.

  The call to 'initiate-search' is needed in any case. It returns a Short
  Web Link (SWL), for example https://d91.io/abc123. This web link can be used to
  display the search results and updates that may happen to the events found.

  The terminate call will stop the updates. Even though not mandatory, it is
  recommended to call terminate at some point after each query.

  A call to 'retrieve-swl-data' can be used to retrieve the results as a JSON
  stream. This call requires the path of the short web link returned by
  'initiate-search', in this example abc123, as a parameter.

  Some search types provide additional data that can be retrieved in a second
  step by performing an 'additional-data-search'.

  2022-01-28
""" 

