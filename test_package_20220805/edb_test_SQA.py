#----- Global Configuration Variables -----

verbose = False        # can be changed via command line parameter
printResults = False   # can be changed via command line parameter
waitTime = 15          # seconds, can be changed via command line parameter

# Settings provided by Intrado
baseUrl = 'https://broker.sqa.powerdata.west.com'
orgId = '4440004000'

"""
  You will need a private key to sign your JWTs. The key length can be either 1024, 2048 or 4096 bit.

  A password protected private key with a length of 2048 bit can be generated like this:
    openssl genrsa -aes256 -passout file:passphrase.txt -out key.private.pem 2048

  A private key without a password can be generated like this:
    openssl genrsa -out key.private.pem 2048

  The public key can be extracted with the following command:
    openssl rsa -in key.private.pem -passin file:passphrase.txt -outform PEM -pubout -out key.public.pem
  Intrado will have to load your public into the EDB configuration.

  During testing, we'll use keys generated by Intrado, but in production you should create your
  own key pair.
"""

# Key for signing the JWTs
keystore_PrivateKeyFile = 'key2048_sqa.private.pem'
keystore_PassPhraseFile = 'passphrase.txt'


